"""Environment-context view of real rows and generated CSDI windows.

Unlike table_raw_real_vs_generated.py, generated voltages are reconstructed with
the source anchor window baseline, not the held-out test date baseline. The table
also carries the source anchor Temp/Hum rows used as context. Temp/Hum are not
generated by CSDI; they are shown only to expose the environmental context.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from openpyxl.styles import Alignment, Font, PatternFill

HERE = Path(__file__).resolve().parent
RUNS = HERE / "runs"
FIXED = RUNS / "upstream_gpu_full_20260910"
DATES = ("250605", "250626", "250718")
SEEDS = (42, 123, 2024)
METHOD = "CSDI"
KEY = "projected"
N_WINDOWS = 120
ND = 4
DISPLAY_FLOOR = 1e-4
COLS = [
    "test_date", "source", "source_date", "time", "Measure4", "Measure7",
    "Temp4", "Hum4", "Temp7", "Hum7", "error",
]


def load_pool(test_date):
    frames = []
    for seed in SEEDS:
        d = np.load(FIXED / METHOD / f"seed{seed}" / test_date / "synthetic.npz")
        frames.append(pd.DataFrame({
            "seed": seed,
            "label": d["label"],
            "anchor_id": d["anchor_ids"],
            "m4_residual": list(d[KEY][:, :, 0]),
            "m7_residual": list(d[KEY][:, :, 1]),
        }))
    return pd.concat(frames, ignore_index=True)


def main():
    meta = pd.read_json(FIXED / "metadata.json", dtype={"date": str}).reset_index(drop=True)
    audit = pd.read_csv(FIXED / "paired_row_audit.csv", dtype={"date": str})
    audit_by_row4 = {(str(r.date), int(r.row4)): r for r in audit.itertuples(index=False)}

    combined, sizes = [], {}
    out_xlsx = RUNS / "env_context_real_vs_generated.xlsx"
    with pd.ExcelWriter(out_xlsx, engine="openpyxl") as xl:
        for test_date in DATES:
            g = audit[audit.date == test_date].sort_values("dt")
            real = pd.DataFrame({
                "test_date": test_date,
                "source": "real",
                "source_date": test_date,
                "time": g.time4,
                "Measure4": g.Measure4,
                "Measure7": g.Measure7,
                "Temp4": g.Temp4,
                "Hum4": g.Hum4,
                "Temp7": g.Temp7,
                "Hum7": g.Hum7,
                "error": g.error4.astype(int),
            })

            pool = load_pool(test_date)
            pick = np.random.default_rng(20240502).choice(len(pool), N_WINDOWS, replace=False)
            rows = []
            for i in pick:
                r = pool.iloc[i]
                anchor = meta.iloc[int(r.anchor_id)]
                source_date = str(anchor.date)
                row4_ids = list(anchor.row4)
                for step in range(4):
                    env = audit_by_row4[(source_date, int(row4_ids[step]))]
                    rows.append({
                        "test_date": test_date,
                        "source": METHOD,
                        "source_date": source_date,
                        "time": "",
                        "Measure4": float(r.m4_residual[step]) + float(anchor.base4),
                        "Measure7": float(r.m7_residual[step]) + float(anchor.base7),
                        "Temp4": float(env.Temp4),
                        "Hum4": float(env.Hum4),
                        "Temp7": float(env.Temp7),
                        "Hum7": float(env.Hum7),
                        "error": int(r.label),
                    })
            gen = pd.DataFrame(rows)
            gen[["Measure4", "Measure7"]] = gen[["Measure4", "Measure7"]].clip(lower=DISPLAY_FLOOR)
            part = pd.concat([real, gen], ignore_index=True)[COLS]
            numeric = ["Measure4", "Measure7", "Temp4", "Hum4", "Temp7", "Hum7"]
            part[numeric] = part[numeric].round(ND)
            part.to_excel(xl, sheet_name=test_date, index=False)

            ws = xl.sheets[test_date]
            for cell in ws[1]:
                cell.font = Font(bold=True)
                cell.alignment = Alignment(horizontal="center")
            fill = PatternFill("solid", fgColor="E2F0D9")
            for row in range(2, ws.max_row + 1):
                is_gen = ws.cell(row, 2).value != "real"
                for col in range(1, len(COLS) + 1):
                    ws.cell(row, col).alignment = Alignment(horizontal="center")
                    if is_gen:
                        ws.cell(row, col).fill = fill
                for col in (5, 6, 7, 8, 9, 10):
                    ws.cell(row, col).number_format = "0.0000"
            ws.freeze_panes = "A2"
            widths = [10, 8, 12, 21, 12, 12, 10, 10, 10, 10, 7]
            for col, width in zip("ABCDEFGHIJK", widths):
                ws.column_dimensions[col].width = width

            combined.append(part)
            sizes[test_date] = (len(real), len(gen))

        pd.DataFrame({
            "item": [
                "Purpose", "Generated voltage", "Temp/Hum columns", "source_date", "Caveat",
                "Rows", "Decimals",
            ],
            "note": [
                "A less misleading physical view of existing CSDI samples with environment context.",
                "Projected generated residual + source anchor baseline, not held-out test-date baseline.",
                "Not generated; copied from the source anchor window to show environmental context.",
                "Date of the real window used as CSDI anchor/context for that generated window.",
                "This is still not a true environment-conditioned generator; it only audits and displays the current model more honestly.",
                "; ".join(f"{d}: {v[0]} real + {v[1]} generated" for d, v in sizes.items()),
                "All numeric values rounded to 4 decimals; generated projected voltages below 0.0001 are displayed as 0.0001.",
            ],
        }).to_excel(xl, sheet_name="notes", index=False)
        ws = xl.sheets["notes"]
        ws.column_dimensions["A"].width = 24
        ws.column_dimensions["B"].width = 110
        for cell in ws[1]:
            cell.font = Font(bold=True)
        for row in range(2, ws.max_row + 1):
            ws.cell(row, 1).alignment = Alignment(wrap_text=True, vertical="top")
            ws.cell(row, 2).alignment = Alignment(wrap_text=True, vertical="top")

    out_csv = RUNS / "env_context_real_vs_generated.csv"
    pd.concat(combined, ignore_index=True).to_csv(out_csv, index=False, encoding="utf-8-sig")
    for date, (n_real, n_gen) in sizes.items():
        print(f"{date}: {n_real} real rows + {n_gen} generated rows")
    print("wrote", out_xlsx)
    print("wrote", out_csv)


if __name__ == "__main__":
    main()
